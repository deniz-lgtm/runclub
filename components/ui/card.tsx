import * as React from "react";
import { cn } from "@/lib/utils";

/**
 * Card — sharper corners, flatter shadows, thinner borders than
 * the starter shadcn Card. Looks like a trim card on a press sheet.
 */
export const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-sm border border-ink/10 bg-surface shadow-flat",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

